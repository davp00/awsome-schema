    out.push(
        "    serde_json::to_value(value).map_err(|error| ClientError::new(error.to_string()))",
    );
    out.push("}");
    out.blank();
    out.push("#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]");
    out.push("#[serde(rename_all = \"lowercase\")]");
    out.push("pub enum SortDir { Asc, Desc }");
    out.blank();
    out.push("#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]");
    out.push("pub enum MutationReturnMode {");
    out.push("    #[serde(rename = \"NONE\")] None,");
    out.push("    #[serde(rename = \"BEFORE\")] Before,");
    out.push("    #[serde(rename = \"AFTER\")] After,");
    out.push("    #[serde(rename = \"DIFF\")] Diff,");
    out.push("}");
    out.blank();
    out.push("#[derive(Clone, Debug, Serialize, Deserialize)]");
    out.push("#[serde(untagged)]");
    out.push("pub enum LinkWrite { Id(String), Bag(Value) }");
    out.blank();
    out.push("#[derive(Clone, Debug, Serialize, Deserialize)]");
    out.push("#[serde(untagged)]");
    out.push("pub enum OneOrMany<T> { One(T), Many(Vec<T>) }");
    out.blank();
    out.push("#[derive(Clone, Debug, Default, Serialize, Deserialize)]");
    out.push("pub struct NestedSelect<S, O> {");
    out.push("    #[serde(skip_serializing_if = \"Option::is_none\")]");
    out.push("    pub select: Option<Box<S>>,");
    out.push("    #[serde(rename = \"orderBy\", skip_serializing_if = \"Option::is_none\")]");
    out.push("    pub order_by: Option<O>,");
    out.push("    #[serde(skip_serializing_if = \"Option::is_none\")]");
