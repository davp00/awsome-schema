fn emit_struct_open(out: &mut Out, name: &str, deserialize: bool, default: bool) {
    let mut derives = vec!["Clone", "Debug", "Serialize"];
    if deserialize {
        derives.push("Deserialize");
    }
    if default {
        derives.push("Default");
    }
    out.push(format!("#[derive({})]", derives.join(", ")));
    out.push(format!("pub struct {name} {{"));
}

fn emit_logic_fields(out: &mut Out, name: &str) {
    out.push("    #[serde(rename = \"AND\", skip_serializing_if = \"Option::is_none\")]");
    out.push(format!("    pub and: Option<Vec<{name}>>,"));
    out.push("    #[serde(rename = \"OR\", skip_serializing_if = \"Option::is_none\")]");
    out.push(format!("    pub or: Option<Vec<{name}>>,"));
    out.push("    #[serde(rename = \"NOT\", skip_serializing_if = \"Option::is_none\")]");
    out.push(format!("    pub not: Option<Vec<{name}>>,"));
}

fn push_field(
    out: &mut Out,
    ident: &str,
    ty: &str,
    rename: Option<&str>,
    skip_none: bool,
    default: bool,
) {
    if let Some(rename) = rename {
        let mut pieces = vec![format!("rename = \"{}\"", escape(rename))];
        if skip_none {
            pieces.push("skip_serializing_if = \"Option::is_none\"".to_owned());
        }
        if default {
            pieces.push("default".to_owned());
        }
        out.push(format!("    #[serde({})]", pieces.join(", ")));
    } else if skip_none || default {
        let mut pieces = Vec::new();
        if skip_none {
            pieces.push("skip_serializing_if = \"Option::is_none\"");
        }
        if default {
            pieces.push("default");
        }
        out.push(format!("    #[serde({})]", pieces.join(", ")));
    }
    out.push(format!("    pub {ident}: {ty},"));
}

fn collect_items<'a>(schema: &'a DatabaseSchema, naming: &NamingContext<'_>) -> Vec<Item<'a>> {
    let mut items = Vec::new();
    for model in &schema.models {
        items.push(Item {
            name: &model.name,
            table: model.table_name(naming.convention()),
            cols: model_cols(schema, model, naming),
            edge: None,
        });
    }
    for edge in &schema.edges {
        items.push(Item {
            name: &edge.name,
            table: edge.table_name(naming.convention()),
            cols: edge_cols(schema, edge, naming),
            edge: Some(EdgeEnds {
                in_table: table_for(schema, &edge.in_model, naming),
                out_table: table_for(schema, &edge.out_model, naming),
            }),
        });
    }
    items
}

fn model_cols(schema: &DatabaseSchema, model: &Model, naming: &NamingContext<'_>) -> Vec<Col> {
    let mut cols = Vec::new();
    if !model.fields.iter().any(|field| field.is_id) {
        cols.push(id_col());
    }
    for field in model.fields.iter().filter(|field| !field.name.contains('.')) {
        cols.push(col_from_field(schema, &model.name, field, naming));
    }
    cols
}

fn edge_cols(schema: &DatabaseSchema, edge: &Edge, naming: &NamingContext<'_>) -> Vec<Col> {
    let mut cols = vec![
        id_col(),
        Col {
            json: "in".to_owned(),
            ident: "r#in".to_owned(),
            kind: Kind::Stored { target: edge.in_model.clone(), list: false },
            optional: false,
            is_id: false,
            unique: false,
        },
        Col {
            json: "out".to_owned(),
            ident: "r#out".to_owned(),
            kind: Kind::Stored { target: edge.out_model.clone(), list: false },
            optional: false,
            is_id: false,
            unique: false,
        },
    ];
    for field in edge.fields.iter().filter(|field| !field.name.contains('.')) {
        cols.push(col_from_field(schema, &edge.name, field, naming));
    }
    cols
}

fn id_col() -> Col {
    Col {
        json: "id".to_owned(),
        ident: "id".to_owned(),
        kind: Kind::Scalar { rust: "String".to_owned(), filter: Filter::Id, numeric: false },
        optional: false,
        is_id: true,
        unique: true,
    }
}

fn col_from_field(
    schema: &DatabaseSchema,
    owner: &str,
    field: &Field,
    naming: &NamingContext<'_>,
) -> Col {
    let json = naming.field_name(field);
    let (ident, _) = rust_ident(&json);
    let kind = if let Some(relation) = &field.relation_name {
        let edge_name = resolve_edge(schema, relation);
        let edge = schema.edges.iter().find(|edge| edge.name == edge_name);
        let dir = edge.map_or("out", |edge| if edge.in_model == owner { "out" } else { "in" });
        Kind::Relation {
            edge: edge_name,
            list: field.is_list_link() || matches!(field.field_type, FieldType::Array(_)),
            dir,
        }
    } else if field.is_link() {
        let target = link_target(field);
        let list = field.is_list_link();
        if field.is_computed_link() {
            Kind::Computed { target, list }
        } else {
            Kind::Stored { target, list }
        }
    } else if let Some(object) = named_object(schema, field) {
        Kind::Object { type_name: object.name.clone() }
    } else {
        let filter = if field.is_id { Filter::Id } else { filter_of(&field.field_type, false) };
        Kind::Scalar {
            rust: if field.is_id { "String".to_owned() } else { rust_scalar(&field.field_type) },
            filter,
            numeric: matches!(field.field_type, FieldType::Int | FieldType::Float),
        }
    };
    Col { json, ident, kind, optional: field.optional, is_id: field.is_id, unique: field.unique }
}

fn record_ty(col: &Col) -> String {
    match &col.kind {
        Kind::Scalar { rust, .. } | Kind::Object { type_name: rust } => opt(rust, col.optional),
        Kind::Stored { list: true, .. } => opt("Vec<String>", col.optional),
        Kind::Stored { list: false, .. } => opt("String", col.optional),
        Kind::Computed { .. } | Kind::Relation { .. } => "Value".to_owned(),
    }
}

fn selected_ty(col: &Col) -> (String, bool) {
    match &col.kind {
        Kind::Scalar { rust, .. } | Kind::Object { type_name: rust } => {
            (opt(rust, col.optional), col.optional)
        }
        Kind::Stored { target, list: false } => {
            (opt(&format!("{target}Selected"), col.optional), col.optional)
        }
        Kind::Stored { target, list: true } => {
            (opt(&format!("Vec<{target}Selected>"), col.optional), col.optional)
        }
        Kind::Computed { target, list: true } => (format!("Option<Vec<{target}Selected>>"), true),
        Kind::Computed { target, list: false } => (format!("Option<{target}Selected>"), true),
        Kind::Relation { edge, list: true, .. } => (format!("Option<Vec<{edge}Selected>>"), true),
        Kind::Relation { edge, list: false, .. } => (format!("Option<{edge}Selected>"), true),
    }
}

fn where_ty(col: &Col) -> String {
    match &col.kind {
        Kind::Scalar { filter, .. } => filter.name().to_owned(),
        Kind::Object { type_name } => format!("{type_name}Where"),
        Kind::Stored { target, list: true } | Kind::Computed { target, list: true } => {
            format!("RelationFilter<{target}Where>")
        }
        Kind::Stored { target, list: false } | Kind::Computed { target, list: false } => {
            format!("Box<{target}Where>")
        }
        Kind::Relation { edge, list: true, .. } => format!("RelationFilter<{edge}Where>"),
        Kind::Relation { edge, list: false, .. } => format!("Box<{edge}Where>"),
    }
}

fn order_ty(col: &Col) -> Option<&'static str> {
    match &col.kind {
        Kind::Scalar { .. } => Some("SortDir"),
        Kind::Stored { list: true, .. }
        | Kind::Computed { list: true, .. }
        | Kind::Relation { list: true, .. } => Some("RelationCountOrder"),
        _ => None,
    }
}

fn select_ty(col: &Col) -> String {
    match &col.kind {
        Kind::Scalar { .. } | Kind::Object { .. } => "bool".to_owned(),
        Kind::Stored { target, .. } | Kind::Computed { target, .. } => {
            format!("NestedSelect<{target}Select, {target}OrderBy>")
        }
        Kind::Relation { edge, .. } => format!("NestedSelect<{edge}Select, {edge}OrderBy>"),
    }
}

fn select_meta_expr(schema: &DatabaseSchema, naming: &NamingContext<'_>, col: &Col) -> String {
    match &col.kind {
        Kind::Scalar { filter, .. } => format!("FieldSelectMeta::scalar({})", filter.meta()),
        Kind::Object { type_name } => {
            let object = schema.object_types.iter().find(|object| object.name == *type_name);
            let mut fields =
                String::from("{ let mut object_fields = std::collections::BTreeMap::new();");
            if let Some(object) = object {
                for field in &object.fields {
                    let key = naming.field_name_str(&field.name, &BTreeMap::new());
                    let filter = filter_of(&field.field_type, false);
                    let _ = write!(
                        fields,
                        " object_fields.insert({}.to_owned(), FieldSelectMeta::scalar({}));",
                        rust_string(&key),
                        filter.meta()
                    );
                }
            }
            fields.push_str(" FieldSelectMeta::Object { fields: object_fields } }");
            fields
        }
        Kind::Stored { target, list } => format!(
            "FieldSelectMeta::Stored {{ target_table: {}.to_owned(), list: {list} }}",
            rust_string(&table_for(schema, target, naming))
        ),
        Kind::Computed { target, list } => format!(
            "FieldSelectMeta::Computed {{ target_table: {}.to_owned(), list: {list} }}",
            rust_string(&table_for(schema, target, naming))
        ),
        Kind::Relation { edge, list, dir } => {
            let edge_table = schema
                .edges
                .iter()
                .find(|item| item.name == *edge)
                .map_or_else(|| edge.clone(), |item| item.table_name(naming.convention()));
            let dir = if *dir == "out" { "RelationDir::Out" } else { "RelationDir::In" };
            format!(
                "FieldSelectMeta::Edge {{ edge_table: {}.to_owned(), dir: {dir}, list: {list} }}",
                rust_string(&edge_table)
            )
        }
    }
}

fn write_meta_expr(
    schema: &DatabaseSchema,
    naming: &NamingContext<'_>,
    item: &Item<'_>,
    col: &Col,
) -> Option<String> {
    match &col.kind {
        Kind::Scalar { .. } | Kind::Object { .. } => Some("FieldWriteMeta::Scalar".to_owned()),
        Kind::Stored { target, list } => {
            let unique = unique_fields(schema, target, naming);
            Some(format!(
                "FieldWriteMeta::Stored {{ target_table: {}.to_owned(), list: {list}, optional: {}, unique_fields: vec![{unique}] }}",
                rust_string(&table_for(schema, target, naming)),
                col.optional
            ))
        }
        Kind::Computed { target, list } => {
            let back =
                opposite_field(schema, item.name, col, naming).unwrap_or_else(|| "id".to_owned());
            let back_optional = opposite_optional(schema, item.name, col).unwrap_or(false);
            let unique = unique_fields(schema, target, naming);
            Some(format!(
                "FieldWriteMeta::Computed {{ target_table: {}.to_owned(), list: {list}, back_link_field: {}.to_owned(), back_link_optional: {back_optional}, unique_fields: vec![{unique}] }}",
                rust_string(&table_for(schema, target, naming)),
                rust_string(&back)
            ))
        }
        Kind::Relation { edge, list, dir } => {
            let found = schema.edges.iter().find(|item| item.name == *edge)?;
            let payload = found
                .fields
                .iter()
                .filter(|field| !field.name.contains('.'))
                .map(|field| format!("{}.to_owned()", rust_string(&naming.field_name(field))))
                .collect::<Vec<_>>()
                .join(", ");
            let dir = if *dir == "out" { "RelationDir::Out" } else { "RelationDir::In" };
            Some(format!(
                "FieldWriteMeta::Edge {{ edge_table: {}.to_owned(), dir: {dir}, list: {list}, in_table: {}.to_owned(), out_table: {}.to_owned(), payload_fields: vec![{payload}] }}",
                rust_string(&found.table_name(naming.convention())),
                rust_string(&table_for(schema, &found.in_model, naming)),
                rust_string(&table_for(schema, &found.out_model, naming))
            ))
        }
    }
}

fn unique_fields(schema: &DatabaseSchema, model_name: &str, naming: &NamingContext<'_>) -> String {
    let Some(model) = schema.models.iter().find(|model| model.name == model_name) else {
        return String::new();
    };
    model
        .fields
        .iter()
        .filter(|field| {
            field.unique && !field.is_id && !field.is_link() && field.relation_name.is_none()
        })
        .map(|field| format!("{}.to_owned()", rust_string(&naming.field_name(field))))
        .collect::<Vec<_>>()
        .join(", ")
}

fn opposite_field(
    schema: &DatabaseSchema,
    _owner: &str,
    col: &Col,
    naming: &NamingContext<'_>,
) -> Option<String> {
    let Kind::Computed { target, .. } = &col.kind else { return None };
    let model = schema.models.iter().find(|model| model.name == *target)?;
    let link_name = model.fields.iter().find_map(|field| {
        if field.is_computed_link() && naming.field_name(field) == col.json {
            field.link_name.clone()
        } else {
            None
        }
    });
    // The computed field lives on the owner, not the target. Search owner fields via schema.
    let owner = schema.models.iter().find(|model| {
        model
            .fields
            .iter()
            .any(|field| field.is_computed_link() && naming.field_name(field) == col.json)
    })?;
    let computed = owner
        .fields
        .iter()
        .find(|field| field.is_computed_link() && naming.field_name(field) == col.json)?;
    let link_name = computed.link_name.as_deref().or(link_name.as_deref())?;
    model
        .fields
        .iter()
        .find(|field| field.is_stored_link() && field.link_name.as_deref() == Some(link_name))
        .map(|field| naming.field_name(field))
}

fn opposite_optional(schema: &DatabaseSchema, _owner: &str, col: &Col) -> Option<bool> {
    let Kind::Computed { target, .. } = &col.kind else { return None };
    let owner = schema
        .models
        .iter()
        .find(|model| model.fields.iter().any(|field| naming_matches_computed(field, &col.json)))?;
    let computed = owner.fields.iter().find(|field| naming_matches_computed(field, &col.json))?;
    let link_name = computed.link_name.as_deref()?;
    let model = schema.models.iter().find(|model| model.name == *target)?;
    model
        .fields
        .iter()
        .find(|field| field.is_stored_link() && field.link_name.as_deref() == Some(link_name))
        .map(|field| field.optional)
}

fn naming_matches_computed(field: &Field, json: &str) -> bool {
    field.is_computed_link()
        && (field.name == json || field.attributes.get("map").is_some_and(|mapped| mapped == json))
}

impl Col {
    fn is_scalar_group(&self) -> bool {
        matches!(self.kind, Kind::Scalar { .. })
    }

    fn is_numeric(&self) -> bool {
        matches!(self.kind, Kind::Scalar { numeric: true, .. })
    }
}

fn named_object<'a>(schema: &'a DatabaseSchema, field: &Field) -> Option<&'a ObjectTypeDefinition> {
    if let Some(name) = field.object_type_name.as_deref() {
        return schema.object_types.iter().find(|object| object.name == name);
    }
    if let FieldType::Model(name) = &field.field_type {
        return schema.object_types.iter().find(|object| object.name == *name);
    }
    None
}

fn link_target(field: &Field) -> String {
    field
        .link_target
        .clone()
        .or_else(|| field.field_type.link_model_name().map(ToOwned::to_owned))
        .unwrap_or_else(|| "Unknown".to_owned())
}

fn resolve_edge(schema: &DatabaseSchema, relation_name: &str) -> String {
    schema
        .edges
        .iter()
        .find(|edge| {
            edge.name == relation_name
                || edge.table_name(&schema.naming) == relation_name
                || edge.attributes.get("map").is_some_and(|mapped| mapped == relation_name)
        })
        .map_or_else(|| relation_name.to_owned(), |edge| edge.name.clone())
}

fn table_for(schema: &DatabaseSchema, model_name: &str, naming: &NamingContext<'_>) -> String {
    schema.models.iter().find(|model| model.name == model_name).map_or_else(
        || naming.convention().tables.apply(model_name),
        |model| model.table_name(naming.convention()),
    )
}

fn rust_scalar(field_type: &FieldType) -> String {
    match field_type {
        FieldType::String | FieldType::Datetime | FieldType::RecordId(_) | FieldType::Model(_) => {
            "String".to_owned()
        }
        FieldType::Int => "i64".to_owned(),
        FieldType::Float => "f64".to_owned(),
        FieldType::Bool => "bool".to_owned(),
        FieldType::Object => "Value".to_owned(),
        FieldType::Array(inner) => format!("Vec<{}>", rust_scalar(inner)),
        FieldType::Custom(value) => sanitize_type(value),
    }
}

fn filter_of(field_type: &FieldType, is_id: bool) -> Filter {
    if is_id {
        return Filter::Id;
    }
    match field_type {
        FieldType::String => Filter::String,
        FieldType::Int | FieldType::Float => Filter::Number,
        FieldType::Bool => Filter::Boolean,
        FieldType::Datetime => Filter::Datetime,
        FieldType::Array(_) => Filter::Array,
        FieldType::RecordId(_) => Filter::Id,
        FieldType::Object | FieldType::Model(_) | FieldType::Custom(_) => Filter::Json,
    }
}

fn opt(ty: &str, optional: bool) -> String {
    if optional { format!("Option<{ty}>") } else { ty.to_owned() }
}

fn rust_ident(json: &str) -> (String, Option<String>) {
    let snake = NamingCase::SnakeCase.apply(json);
    let raw = KEYWORDS.contains(&snake.as_str());
    let ident = if raw { format!("r#{snake}") } else { snake.clone() };
    let rename = if snake == json { None } else { Some(json.to_owned()) };
    (ident, rename)
}

fn rename_of(col: &Col) -> Option<&str> {
    let snake = NamingCase::SnakeCase.apply(&col.json);
    if snake == col.json { None } else { Some(col.json.as_str()) }
}

fn variant_name(json: &str) -> String {
    let snake = NamingCase::SnakeCase.apply(json);
    let mut chars = snake.split('_').filter(|part| !part.is_empty());
    let mut name = String::new();
    for part in chars.by_ref() {
        let mut letters = part.chars();
        if let Some(first) = letters.next() {
            name.push(first.to_ascii_uppercase());
            name.extend(letters);
        }
    }
    if name.is_empty() { "Field".to_owned() } else { name }
}

fn client_method(name: &str) -> String {
    rust_ident(name).0
}

fn sanitize_type(value: &str) -> String {
    let cleaned: String =
        value.chars().filter(|ch| ch.is_ascii_alphanumeric() || *ch == '_' || *ch == ':').collect();
    if cleaned.is_empty() { "Value".to_owned() } else { cleaned }
}

fn rust_string(value: &str) -> String {
    format!("\"{}\"", escape(value))
}

fn escape(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}
