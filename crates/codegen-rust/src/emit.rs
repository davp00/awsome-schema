    out.push("    #[serde(skip_serializing_if = \"Option::is_none\")]");
    out.push("    pub skip: Option<u64>,");
    out.push("}");
    out.blank();
    out.push("#[derive(Clone, Debug, Serialize, Deserialize)]");
    out.push("pub struct RelationCountOrder {");
    out.push("    #[serde(rename = \"_count\")]");
    out.push("    pub count: SortDir,");
