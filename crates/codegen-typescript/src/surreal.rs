use super::TypeScriptProvider;
use super::types::table_for_model_name;
use core::{DatabaseSchema, DomainError, Edge, Model, NamingContext};

pub struct SurrealTypeScriptProvider;

impl TypeScriptProvider for SurrealTypeScriptProvider {
    fn id(&self) -> &'static str {
        "surrealdb"
    }

    fn emit(&self, schema: &DatabaseSchema) -> Result<String, DomainError> {
        Ok(emit_typescript(schema))
    }
}

