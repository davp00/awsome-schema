fn emit_build_order_by(out: &mut Vec<String>) {
    out.push("function relationCountExpr(".to_owned());
    out.push("  key: string,".to_owned());
    out.push("  fieldMeta: FieldSelectMeta,".to_owned());
    out.push("): string | null {".to_owned());
    out.push("  if (!fieldMeta.list) return null;".to_owned());
    out.push("  if (fieldMeta.kind === \"edge\") {".to_owned());
    out.push(
        "    const arrow = fieldMeta.dir === \"out\" ? `->${fieldMeta.edgeTable}` : `<-${fieldMeta.edgeTable}`;"
            .to_owned(),
    );
    out.push("    return `array::len(${arrow})`;".to_owned());
    out.push("  }".to_owned());
    out.push(
        "  if (fieldMeta.kind === \"stored\" || fieldMeta.kind === \"computed\") {".to_owned(),
    );
    out.push("    return `array::len(${key})`;".to_owned());
    out.push("  }".to_owned());
    out.push("  return null;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push("function orderByCountAlias(key: string): string {".to_owned());
    out.push("  return `__ob_${key}`;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push("function collectOrderByCountProjections(".to_owned());
    out.push(
        "  orderBy: Record<string, unknown> | Record<string, unknown>[] | undefined,".to_owned(),
    );
    out.push("  table: string,".to_owned());
    out.push(
        "  allMeta: Record<string, Record<string, FieldSelectMeta>> = SelectMetaByTable,"
            .to_owned(),
    );
    out.push("): string[] {".to_owned());
    out.push("  if (!orderBy) return [];".to_owned());
    out.push("  const items = Array.isArray(orderBy) ? orderBy : [orderBy];".to_owned());
    out.push("  const meta = allMeta[table] ?? {};".to_owned());
    out.push("  const parts: string[] = [];".to_owned());
    out.push("  const seen = new Set<string>();".to_owned());
    out.push("  for (const item of items) {".to_owned());
    out.push("    if (!item || typeof item !== \"object\") continue;".to_owned());
    out.push("    for (const [key, value] of Object.entries(item)) {".to_owned());
    out.push(
        "      if (!value || typeof value !== \"object\" || Array.isArray(value) || !(\"_count\" in value)) continue;"
            .to_owned(),
    );
    out.push("      const dir = (value as { _count?: unknown })._count;".to_owned());
    out.push("      if (dir !== \"asc\" && dir !== \"desc\") continue;".to_owned());
    out.push("      const fieldMeta = meta[key];".to_owned());
    out.push("      if (!fieldMeta) continue;".to_owned());
    out.push("      const expr = relationCountExpr(key, fieldMeta);".to_owned());
    out.push("      if (!expr || seen.has(key)) continue;".to_owned());
    out.push("      seen.add(key);".to_owned());
    out.push("      parts.push(`${expr} AS ${orderByCountAlias(key)}`);".to_owned());
    out.push("    }".to_owned());
    out.push("  }".to_owned());
    out.push("  return parts;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push("function stripOrderByCountFields<T>(rows: T[]): T[] {".to_owned());
    out.push("  return rows.map((row) => {".to_owned());
    out.push("    if (!row || typeof row !== \"object\") return row;".to_owned());
    out.push("    const out = { ...(row as Record<string, unknown>) };".to_owned());
    out.push("    for (const key of Object.keys(out)) {".to_owned());
    out.push("      if (key.startsWith(\"__ob_\")) delete out[key];".to_owned());
    out.push("    }".to_owned());
    out.push("    return out as T;".to_owned());
    out.push("  });".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push("function buildOrderBy(".to_owned());
    out.push(
        "  orderBy: Record<string, unknown> | Record<string, unknown>[] | undefined,".to_owned(),
    );
    out.push("  table: string,".to_owned());
    out.push(
        "  allMeta: Record<string, Record<string, FieldSelectMeta>> = SelectMetaByTable,"
            .to_owned(),
    );
    out.push("): string {".to_owned());
    out.push("  if (!orderBy) return \"\";".to_owned());
    out.push("  const items = Array.isArray(orderBy) ? orderBy : [orderBy];".to_owned());
    out.push("  const meta = allMeta[table] ?? {};".to_owned());
    out.push("  const parts: string[] = [];".to_owned());
    out.push("  for (const item of items) {".to_owned());
    out.push("    if (!item || typeof item !== \"object\") continue;".to_owned());
    out.push("    for (const [key, value] of Object.entries(item)) {".to_owned());
    out.push("      const fieldMeta = meta[key];".to_owned());
    out.push("      if (!fieldMeta) continue;".to_owned());
    out.push("      if (value === \"asc\" || value === \"desc\") {".to_owned());
    out.push("        if (fieldMeta.kind !== \"scalar\") continue;".to_owned());
    out.push("        parts.push(`${key} ${value.toUpperCase()}`);".to_owned());
    out.push("        continue;".to_owned());
    out.push("      }".to_owned());
    out.push(
        "      if (value && typeof value === \"object\" && !Array.isArray(value) && \"_count\" in value) {"
            .to_owned(),
    );
    out.push("        const dir = (value as { _count?: unknown })._count;".to_owned());
    out.push("        if (dir !== \"asc\" && dir !== \"desc\") continue;".to_owned());
    out.push("        if (!relationCountExpr(key, fieldMeta)) continue;".to_owned());
    out.push(
        "        parts.push(`${orderByCountAlias(key)} ${String(dir).toUpperCase()}`);".to_owned(),
    );
    out.push("      }".to_owned());
    out.push("    }".to_owned());
    out.push("  }".to_owned());
    out.push("  return parts.length === 0 ? \"\" : `ORDER BY ${parts.join(\", \")}`;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push(
        "function nestedLimitClause(take: number | undefined, skip: number | undefined): string {"
            .to_owned(),
    );
    out.push("  let clause = \"\";".to_owned());
    out.push("  if (take !== undefined) {".to_owned());
    out.push("    if (!Number.isFinite(take) || take < 0) throw new Error(\"take must be a non-negative number\");".to_owned());
    out.push("    clause += ` LIMIT ${Math.floor(take)}`;".to_owned());
    out.push("  }".to_owned());
    out.push("  if (skip !== undefined) {".to_owned());
    out.push("    if (!Number.isFinite(skip) || skip < 0) throw new Error(\"skip must be a non-negative number\");".to_owned());
    out.push("    clause += ` START ${Math.floor(skip)}`;".to_owned());
    out.push("  }".to_owned());
    out.push("  return clause;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push("function appendLimitStart(".to_owned());
    out.push("  sql: string,".to_owned());
    out.push("  take: number | undefined,".to_owned());
    out.push("  skip: number | undefined,".to_owned());
    out.push("  vars: Record<string, unknown>,".to_owned());
    out.push("): string {".to_owned());
    out.push("  let out = sql;".to_owned());
    out.push("  if (take !== undefined) {".to_owned());
    out.push("    if (!Number.isFinite(take) || take < 0) throw new Error(\"take must be a non-negative number\");".to_owned());
    out.push("    vars.__take = Math.floor(take);".to_owned());
    out.push("    out = out + \" LIMIT $__take\";".to_owned());
    out.push("  }".to_owned());
    out.push("  if (skip !== undefined) {".to_owned());
    out.push("    if (!Number.isFinite(skip) || skip < 0) throw new Error(\"skip must be a non-negative number\");".to_owned());
    out.push("    vars.__skip = Math.floor(skip);".to_owned());
    out.push("    out = out + \" START $__skip\";".to_owned());
    out.push("  }".to_owned());
    out.push("  return out;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
}

fn emit_build_where(out: &mut Vec<String>) {
    out.push("type WhereBuildCtx = { vars: Record<string, unknown>; n: number };".to_owned());
    out.push(String::new());
    out.push("function nextWhereVar(ctx: WhereBuildCtx, value: unknown): string {".to_owned());
    out.push("  const key = `w${ctx.n++}`;".to_owned());
    out.push("  ctx.vars[key] = value;".to_owned());
    out.push("  return `$${key}`;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push(
        "function isScalarFilterObject(value: unknown): value is Record<string, unknown> {"
            .to_owned(),
    );
    out.push(
        "  if (!value || typeof value !== \"object\" || Array.isArray(value)) return false;"
            .to_owned(),
    );
    out.push(
        "  return [\"equals\", \"in\", \"contains\", \"gt\", \"gte\", \"lt\", \"lte\"].some((k) =>"
            .to_owned(),
    );
    out.push("    Object.prototype.hasOwnProperty.call(value, k),".to_owned());
    out.push("  );".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push("function scalarPredicate(".to_owned());
    out.push("  path: string,".to_owned());
    out.push("  value: unknown,".to_owned());
    out.push("  filter: string,".to_owned());
    out.push("  ctx: WhereBuildCtx,".to_owned());
    out.push("): string[] {".to_owned());
    out.push("  if (value === undefined) return [];".to_owned());
    out.push("  if (!isScalarFilterObject(value)) {".to_owned());
    out.push("    return [`${path} = ${nextWhereVar(ctx, value)}`];".to_owned());
    out.push("  }".to_owned());
    out.push("  const parts: string[] = [];".to_owned());
    out.push("  if (value.equals !== undefined) parts.push(`${path} = ${nextWhereVar(ctx, value.equals)}`);".to_owned());
    out.push(
        "  if (value.in !== undefined) parts.push(`${path} IN ${nextWhereVar(ctx, value.in)}`);"
            .to_owned(),
    );
    out.push("  if (value.contains !== undefined) {".to_owned());
    out.push("    if (filter === \"array\") parts.push(`${path} CONTAINS ${nextWhereVar(ctx, value.contains)}`);".to_owned());
    out.push(
        "    else parts.push(`string::contains(${path}, ${nextWhereVar(ctx, value.contains)})`);"
            .to_owned(),
    );
    out.push("  }".to_owned());
    out.push(
        "  if (value.gt !== undefined) parts.push(`${path} > ${nextWhereVar(ctx, value.gt)}`);"
            .to_owned(),
    );
    out.push(
        "  if (value.gte !== undefined) parts.push(`${path} >= ${nextWhereVar(ctx, value.gte)}`);"
            .to_owned(),
    );
    out.push(
        "  if (value.lt !== undefined) parts.push(`${path} < ${nextWhereVar(ctx, value.lt)}`);"
            .to_owned(),
    );
    out.push(
        "  if (value.lte !== undefined) parts.push(`${path} <= ${nextWhereVar(ctx, value.lte)}`);"
            .to_owned(),
    );
    out.push("  return parts;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push("function relationMode(value: Record<string, unknown>, list: boolean): {".to_owned());
    out.push("  mode: \"some\" | \"every\" | \"none\" | \"is\";".to_owned());
    out.push("  nested: unknown;".to_owned());
    out.push("} {".to_owned());
    out.push("  if (\"some\" in value) return { mode: \"some\", nested: value.some };".to_owned());
    out.push(
        "  if (\"every\" in value) return { mode: \"every\", nested: value.every };".to_owned(),
    );
    out.push("  if (\"none\" in value) return { mode: \"none\", nested: value.none };".to_owned());
    out.push("  if (\"is\" in value) return { mode: \"is\", nested: value.is };".to_owned());
    out.push("  return { mode: list ? \"some\" : \"is\", nested: value };".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push("function listRelationPredicate(".to_owned());
    out.push("  collectionExpr: string,".to_owned());
    out.push("  mode: \"some\" | \"every\" | \"none\" | \"is\",".to_owned());
    out.push("  nestedClause: string,".to_owned());
    out.push("): string | null {".to_owned());
    out.push("  if (mode === \"is\") return null;".to_owned());
    out.push("  if (mode === \"some\") {".to_owned());
    out.push("    return nestedClause".to_owned());
    out.push("      ? `array::len(${collectionExpr}[WHERE ${nestedClause}]) > 0`".to_owned());
    out.push("      : `array::len(${collectionExpr}) > 0`;".to_owned());
    out.push("  }".to_owned());
    out.push("  if (mode === \"every\") {".to_owned());
    out.push("    return nestedClause".to_owned());
    out.push("      ? `array::len(${collectionExpr}[WHERE ${nestedClause}]) = array::len(${collectionExpr})`".to_owned());
    out.push("      : \"true\";".to_owned());
    out.push("  }".to_owned());
    out.push("  return nestedClause".to_owned());
    out.push("    ? `array::len(${collectionExpr}[WHERE ${nestedClause}]) = 0`".to_owned());
    out.push("    : `array::len(${collectionExpr}) = 0`;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
    out.push("function buildWhere(".to_owned());
    out.push("  where: Record<string, unknown> | undefined,".to_owned());
    out.push("  table: string,".to_owned());
    out.push(
        "  allMeta: Record<string, Record<string, FieldSelectMeta>> = SelectMetaByTable,"
            .to_owned(),
    );
    out.push("  ctx: WhereBuildCtx = { vars: {}, n: 0 },".to_owned());
    out.push("  pathPrefix = \"\",".to_owned());
    out.push("): string {".to_owned());
    out.push("  if (!where) return \"\";".to_owned());
    out.push("  const meta = allMeta[table] ?? {};".to_owned());
    out.push("  const parts: string[] = [];".to_owned());
    out.push("  for (const [key, value] of Object.entries(where)) {".to_owned());
    out.push("    if (value === undefined) continue;".to_owned());
    out.push("    if (key === \"AND\") {".to_owned());
    out.push("      const items = Array.isArray(value) ? value : [value];".to_owned());
    out.push("      const inner = items".to_owned());
    out.push("        .map((item) => buildWhere(item as Record<string, unknown>, table, allMeta, ctx, pathPrefix))".to_owned());
    out.push("        .filter(Boolean);".to_owned());
    out.push("      if (inner.length) parts.push(`(${inner.join(\" AND \")})`);".to_owned());
    out.push("      continue;".to_owned());
    out.push("    }".to_owned());
    out.push("    if (key === \"OR\") {".to_owned());
    out.push("      const items = Array.isArray(value) ? value : [value];".to_owned());
    out.push("      const inner = items".to_owned());
    out.push("        .map((item) => buildWhere(item as Record<string, unknown>, table, allMeta, ctx, pathPrefix))".to_owned());
    out.push("        .filter(Boolean);".to_owned());
    out.push("      if (inner.length) parts.push(`(${inner.join(\" OR \")})`);".to_owned());
    out.push("      continue;".to_owned());
    out.push("    }".to_owned());
    out.push("    if (key === \"NOT\") {".to_owned());
    out.push("      const items = Array.isArray(value) ? value : [value];".to_owned());
    out.push("      const inner = items".to_owned());
    out.push("        .map((item) => buildWhere(item as Record<string, unknown>, table, allMeta, ctx, pathPrefix))".to_owned());
    out.push("        .filter(Boolean);".to_owned());
    out.push("      if (inner.length === 1) parts.push(`!(${inner[0]})`);".to_owned());
    out.push(
        "      else if (inner.length > 1) parts.push(`!((${inner.join(\" AND \")}))`);".to_owned(),
    );
    out.push("      continue;".to_owned());
    out.push("    }".to_owned());
    out.push("    const fieldMeta = meta[key];".to_owned());
    out.push("    if (!fieldMeta) continue;".to_owned());
    out.push("    const path = pathPrefix ? `${pathPrefix}.${key}` : key;".to_owned());
    out.push("    if (fieldMeta.kind === \"scalar\") {".to_owned());
    out.push(
        "      parts.push(...scalarPredicate(path, value, fieldMeta.filter, ctx));".to_owned(),
    );
    out.push("      continue;".to_owned());
    out.push("    }".to_owned());
    out.push(
        "    if (!value || typeof value !== \"object\" || Array.isArray(value)) continue;"
            .to_owned(),
    );
    out.push("    const { mode, nested } = relationMode(value as Record<string, unknown>, fieldMeta.list);".to_owned());
    out.push("    if (fieldMeta.kind === \"edge\") {".to_owned());
    out.push("      const arrow = fieldMeta.dir === \"out\" ? `->${fieldMeta.edgeTable}` : `<-${fieldMeta.edgeTable}`;".to_owned());
    out.push("      const nestedClause = buildWhere(".to_owned());
    out.push("        nested as Record<string, unknown> | undefined,".to_owned());
    out.push("        fieldMeta.edgeTable,".to_owned());
    out.push("        allMeta,".to_owned());
    out.push("        ctx,".to_owned());
    out.push("      );".to_owned());
    out.push("      const pred = listRelationPredicate(arrow, mode, nestedClause);".to_owned());
    out.push("      if (pred) parts.push(pred);".to_owned());
    out.push("      continue;".to_owned());
    out.push("    }".to_owned());
    out.push("    if (fieldMeta.list) {".to_owned());
    out.push("      const nestedClause = buildWhere(".to_owned());
    out.push("        nested as Record<string, unknown> | undefined,".to_owned());
    out.push("        fieldMeta.targetTable,".to_owned());
    out.push("        allMeta,".to_owned());
    out.push("        ctx,".to_owned());
    out.push("      );".to_owned());
    out.push("      const pred = listRelationPredicate(path, mode, nestedClause);".to_owned());
    out.push("      if (pred) parts.push(pred);".to_owned());
    out.push("      continue;".to_owned());
    out.push("    }".to_owned());
    out.push("    const nestedClause = buildWhere(".to_owned());
    out.push("      nested as Record<string, unknown> | undefined,".to_owned());
    out.push("      fieldMeta.targetTable,".to_owned());
    out.push("      allMeta,".to_owned());
    out.push("      ctx,".to_owned());
    out.push("      path,".to_owned());
    out.push("    );".to_owned());
    out.push("    if (nestedClause) parts.push(nestedClause);".to_owned());
    out.push("  }".to_owned());
    out.push("  return parts.join(\" AND \");".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
}

