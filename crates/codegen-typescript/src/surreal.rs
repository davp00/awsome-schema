fn emit_select_helpers(out: &mut Vec<String>, schema: &DatabaseSchema, naming: &NamingContext<'_>) {
    for model in &schema.models {
        let table = model.table_name(naming.convention());
        let fetch_fields = fetch_field_names(model, naming);
        let fetch_lit = js_string_array(&fetch_fields);
        out.push(format!(
            "/** Fetch stored `{name}` row (links as RecordId). */",
            name = model.name
        ));
        out.push(format!(
            "export async function select{}(db: SurrealOpsLike, id: RecordId<\"{table}\"> | string): Promise<{} | undefined> {{",
            model.name, model.name
        ));
        out.push(format!("  return selectRecord<{}>(db, \"{table}\", id);", model.name));
        out.push("}".to_owned());
        out.push(String::new());

        out.push(format!(
            "/** Fetch `{name}` with related link/@relation fields expanded. */",
            name = model.name
        ));
        out.push(format!(
            "export async function select{}Related(db: SurrealOpsLike, id: RecordId<\"{table}\"> | string): Promise<{}Selected | undefined> {{",
            model.name, model.name
        ));
        out.push(format!(
            "  return selectRecordRelated<{}Selected>(db, \"{table}\", id, {fetch_lit});",
            model.name
        ));
        out.push("}".to_owned());
        out.push(String::new());
    }

    for edge in &schema.edges {
        let table = edge.table_name(naming.convention());
        out.push(format!("/** Fetch stored `{name}` edge row. */", name = edge.name));
        out.push(format!(
            "export async function select{}(db: SurrealOpsLike, id: RecordId<\"{table}\"> | string): Promise<{} | undefined> {{",
            edge.name, edge.name
        ));
        out.push(format!("  return selectRecord<{}>(db, \"{table}\", id);", edge.name));
        out.push("}".to_owned());
        out.push(String::new());

        out.push(format!("/** Fetch `{name}` edge with `in`/`out` expanded. */", name = edge.name));
        out.push(format!(
            "export async function select{}Related(db: SurrealOpsLike, id: RecordId<\"{table}\"> | string): Promise<{}Selected | undefined> {{",
            edge.name, edge.name
        ));
        out.push(format!(
            "  return selectRecordRelated<{}Selected>(db, \"{table}\", id, [\"in\", \"out\"]);",
            edge.name
        ));
        out.push("}".to_owned());
        out.push(String::new());
    }
}

fn emit_crud_helpers(out: &mut Vec<String>, schema: &DatabaseSchema, naming: &NamingContext<'_>) {
    for model in &schema.models {
        let table = model.table_name(naming.convention());
        out.push(format!(
            "export async function create{}(db: SurrealOpsLike, data: {}CreateInput): Promise<{}> {{",
            model.name, model.name, model.name
        ));
        out.push(format!(
            "  return createWithNested<{}>(db, \"{table}\", data as Record<string, unknown>);",
            model.name
        ));
        out.push("}".to_owned());
        out.push(String::new());

        out.push(format!(
            "export async function update{}(db: SurrealOpsLike, id: RecordId<\"{table}\"> | string, data: {}UpdateInput): Promise<{} | undefined> {{",
            model.name, model.name, model.name
        ));
        out.push(format!(
            "  return updateWithNested<{}>(db, \"{table}\", String(id), data as Record<string, unknown>) as Promise<{} | undefined>;",
            model.name, model.name
        ));
        out.push("}".to_owned());
        out.push(String::new());

        out.push(format!(
            "export async function delete{}(db: SurrealOpsLike, id: RecordId<\"{table}\"> | string): Promise<void> {{",
            model.name
        ));
        out.push(format!("  return deleteRecord(db, \"{table}\", id);"));
        out.push("}".to_owned());
        out.push(String::new());
    }

    for edge in &schema.edges {
        let table = edge.table_name(naming.convention());
        let in_table = table_for_model_name(schema, &edge.in_model, naming);
        let out_table = table_for_model_name(schema, &edge.out_model, naming);
        out.push(format!(
            "export async function create{}(db: SurrealOpsLike, data: {}CreateInput): Promise<{}> {{",
            edge.name, edge.name, edge.name
        ));
        out.push("  const content = Object.fromEntries(".to_owned());
        out.push(
            "    Object.entries(data).filter(([key]) => key !== \"in\" && key !== \"out\"),"
                .to_owned(),
        );
        out.push("  );".to_owned());
        out.push(format!(
            "  return relateEdge(db, \"{table}\", \"{in_table}\", \"{out_table}\", String(data.in), String(data.out), content) as Promise<{}>;",
            edge.name
        ));
        out.push("}".to_owned());
        out.push(String::new());

        out.push(format!(
            "export async function update{}(db: SurrealOpsLike, id: RecordId<\"{table}\"> | string, data: {}UpdateInput): Promise<{} | undefined> {{",
            edge.name, edge.name, edge.name
        ));
        out.push(format!(
            "  return updateRecord<{}>(db, \"{table}\", id, data as Record<string, unknown>);",
            edge.name
        ));
        out.push("}".to_owned());
        out.push(String::new());

        out.push(format!(
            "export async function delete{}(db: SurrealOpsLike, id: RecordId<\"{table}\"> | string): Promise<void> {{",
            edge.name
        ));
        out.push(format!("  return deleteRecord(db, \"{table}\", id);"));
        out.push("}".to_owned());
        out.push(String::new());
    }
}

