fn emit_fluent_client(out: &mut Vec<String>, schema: &DatabaseSchema, naming: &NamingContext<'_>) {
    out.push("async function runTransaction<T>(".to_owned());
    out.push("  db: SurrealLike,".to_owned());
    out.push("  fn: (tx: ReturnType<typeof buildClientDelegates>) => Promise<T>,".to_owned());
    out.push("): Promise<T> {".to_owned());
    out.push("  const txn = await db.beginTransaction();".to_owned());
    out.push("  const tx = buildClientDelegates(txn);".to_owned());
    out.push("  try {".to_owned());
    out.push("    const result = await fn(tx);".to_owned());
    out.push("    await txn.commit();".to_owned());
    out.push("    return result;".to_owned());
    out.push("  } catch (err) {".to_owned());
    out.push("    try {".to_owned());
    out.push("      await txn.cancel();".to_owned());
    out.push("    } catch {".to_owned());
    out.push("      // ignore cancel errors after a failed transaction".to_owned());
    out.push("    }".to_owned());
    out.push("    throw err;".to_owned());
    out.push("  }".to_owned());
    out.push("}".to_owned());
    out.push(String::new());

    out.push("async function openLiveSelect<T>(".to_owned());
    out.push("  db: SurrealLike,".to_owned());
    out.push("  sql: string,".to_owned());
    out.push("  vars?: Record<string, unknown>,".to_owned());
    out.push("): Promise<LiveHandle<T>> {".to_owned());
    out.push("  const trimmed = sql.trim();".to_owned());
    out.push("  if (!/^LIVE\\s+SELECT\\b/i.test(trimmed)) {".to_owned());
    out.push("    throw new Error(\"$live: sql must be a LIVE SELECT statement\");".to_owned());
    out.push("  }".to_owned());
    out.push("  const result = await db.query(trimmed, vars);".to_owned());
    out.push("  const id = Array.isArray(result) ? result[0] : result;".to_owned());
    out.push("  return db.liveOf<T>(id);".to_owned());
    out.push("}".to_owned());
    out.push(String::new());

    out.push("function buildClientDelegates(db: SurrealOpsLike) {".to_owned());
    out.push("  return {".to_owned());

    for model in &schema.models {
        emit_fluent_model_delegate(out, model, naming);
    }
    for edge in &schema.edges {
        emit_fluent_edge_delegate(out, edge, naming);
    }

    out.push(
        "    $queryRaw: <T = unknown>(sql: string, vars?: Record<string, unknown>): Promise<T[]> =>"
            .to_owned(),
    );
    out.push("      queryRows<T>(db, sql, vars),".to_owned());
    out.push(
        "    $executeRaw: (sql: string, vars?: Record<string, unknown>): Promise<unknown> =>"
            .to_owned(),
    );
    out.push("      db.query(sql, vars),".to_owned());

    out.push("  } as const;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());

    out.push("export type TransactionClient = ReturnType<typeof buildClientDelegates>;".to_owned());
    out.push(String::new());
    out.push("export function createClient(db: SurrealLike) {".to_owned());
    out.push("  const base = buildClientDelegates(db);".to_owned());
    out.push("  return {".to_owned());
    out.push("    ...base,".to_owned());
    for model in &schema.models {
        let table = model.table_name(naming.convention());
        emit_session_live(out, &model.name, &table);
    }
    for edge in &schema.edges {
        let table = edge.table_name(naming.convention());
        emit_session_live(out, &edge.name, &table);
    }
    out.push(
        "    $transaction: <T>(fn: (tx: TransactionClient) => Promise<T>): Promise<T> =>"
            .to_owned(),
    );
    out.push("      runTransaction(db, fn),".to_owned());
    out.push(
        "    $live: <T = unknown>(sql: string, vars?: Record<string, unknown>): Promise<LiveHandle<T>> =>"
            .to_owned(),
    );
    out.push("      openLiveSelect<T>(db, sql, vars),".to_owned());
    out.push("  } as const;".to_owned());
    out.push("}".to_owned());
    out.push(String::new());
}

fn emit_session_live(out: &mut Vec<String>, name: &str, table: &str) {
    let key = client_key(name);
    out.push(format!("    {key}: {{"));
    out.push(format!("      ...base.{key},"));
    out.push(format!(
        "      live: (): Promise<LiveHandle<{name}>> => db.live<{name}>(\"{table}\"),"
    ));
    out.push("    },".to_owned());
}

