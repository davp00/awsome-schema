fn client_key(name: &str) -> String {
    let mut chars = name.chars();
    chars
        .next()
        .map_or_else(String::new, |first| first.to_lowercase().collect::<String>() + chars.as_str())
}

fn query_fn_name(name: &str) -> String {
    if name.ends_with('s') { format!("query{name}") } else { format!("query{name}s") }
}

fn query_related_fn_name(name: &str) -> String {
    format!("{}Related", query_fn_name(name))
}

fn js_string_array(items: &[String]) -> String {
    if items.is_empty() {
        "[]".to_owned()
    } else {
        format!(
            "[{}]",
            items.iter().map(|item| format!("\"{item}\"")).collect::<Vec<_>>().join(", ")
        )
    }
}

fn fetch_field_names(model: &Model, naming: &NamingContext<'_>) -> Vec<String> {
    model
        .fields
        .iter()
        .filter(|field| !field.name.contains('.'))
        .filter(|field| field.is_link() || field.relation_name.is_some())
        .map(|field| naming.field_name(field))
        .collect()
}
