    let key = client_key(&edge.name);
    let table = edge.table_name(naming.convention());
    out.push(format!("    {key}: {{"));
    out.push(format!(
        "      findUnique: <S extends {}Select | undefined = undefined>(args: {{",
        edge.name
    ));
    out.push(format!("        where: {}WhereInput;", edge.name));
    out.push("        select?: S;".to_owned());
