#![allow(clippy::missing_errors_doc, clippy::too_many_lines)]

use std::fmt::Write as _;

use codegen::CodeGenerator;
use core::usecases::CodeGeneratorPort;
use core::{
    DatabaseSchema, DomainError, Edge, Field, FieldType, Model, NamingContext, ObjectTypeDefinition,
};

pub struct TypeScriptGenerator;

impl TypeScriptGenerator {
    #[must_use]
    pub const fn new() -> Self {
        Self
    }
}

impl Default for TypeScriptGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl CodeGenerator for TypeScriptGenerator {
    fn language(&self) -> &'static str {
        "typescript"
    }

    fn generate(&self, schema: &DatabaseSchema) -> Result<String, DomainError> {
        Ok(emit_typescript(schema))
    }
}

impl CodeGeneratorPort for TypeScriptGenerator {
    fn generate(&self, schema: &DatabaseSchema) -> Result<String, DomainError> {
        CodeGenerator::generate(self, schema)
    }
}

fn emit_typescript(schema: &DatabaseSchema) -> String {
    let naming = NamingContext::new(&schema.naming, &schema.models);
    let mut out = vec![
        "// Generated by Awesome Schema".to_owned(),
        "// Requires a SurrealDB JS client compatible with SurrealLike (e.g. `surrealdb`).".to_owned(),
        "// Prefer `recordId(Tables.User, key)` for branded ids.".to_owned(),
        String::new(),
        "/** Surreal record id branded by table name. */".to_owned(),
        "export type RecordId<Table extends string = string> =".to_owned(),
        "  string & { readonly __table?: Table };".to_owned(),
        String::new(),
    ];

    for object_type in &schema.object_types {
        emit_object_type(&mut out, object_type, &naming);
    }

    for model in &schema.models {
        emit_model_record(&mut out, schema, model, &naming);
        emit_model_selected(&mut out, schema, model, &naming);
        emit_model_inputs(&mut out, schema, model, &naming);
    }

    for edge in &schema.edges {
        emit_edge_record(&mut out, schema, edge, &naming);
        emit_edge_selected(&mut out, schema, edge, &naming);
        emit_edge_inputs(&mut out, schema, edge, &naming);
    }

    emit_select_type_utils(&mut out);
    for model in &schema.models {
        emit_model_select_payload(&mut out, schema, model, &naming);
    }
    for edge in &schema.edges {
        emit_edge_select_payload(&mut out, schema, edge, &naming);
    }

    emit_where_shared_types(&mut out);
    for model in &schema.models {
        emit_model_where_input(&mut out, schema, model, &naming);
        emit_model_where_unique_input(&mut out, model, &naming);
    }
    for edge in &schema.edges {
        emit_edge_where_input(&mut out, schema, edge, &naming);
        emit_edge_where_unique_input(&mut out, edge, &naming);
    }

    emit_order_by_shared_types(&mut out);
    for model in &schema.models {
        emit_model_order_by_input(&mut out, model, &naming);
        emit_model_aggregate_types(&mut out, model, &naming);
    }
    for edge in &schema.edges {
        emit_edge_order_by_input(&mut out, edge, &naming);
        emit_edge_aggregate_types(&mut out, edge, &naming);
    }

    emit_tables_const(&mut out, schema, &naming);
    emit_select_meta_registry(&mut out, schema, &naming);
    emit_write_meta_registry(&mut out, schema, &naming);
    emit_record_id_helpers(&mut out);
    emit_surreal_like(&mut out);
    emit_shared_runtime(&mut out);
    emit_select_helpers(&mut out, schema, &naming);
    emit_crud_helpers(&mut out, schema, &naming);
    emit_query_helpers(&mut out, schema, &naming);
    emit_fluent_client(&mut out, schema, &naming);

    out.join("\n")
}

fn emit_object_type(out: &mut Vec<String>, object_type: &ObjectTypeDefinition, naming: &NamingContext<'_>) {
    out.push(format!("export type {} = {{", object_type.name));
    for field in &object_type.fields {
        let ts = map_object_field_type(&field.field_type, naming);
        let optional = if field.optional { "?" } else { "" };
        out.push(format!("  {}{optional}: {};", field.name, ts));
    }
    if object_type.flexible {
        out.push("  [key: string]: unknown;".to_owned());
    }
    out.push("};".to_owned());
    out.push(String::new());
}

fn emit_model_record(
    out: &mut Vec<String>,
    schema: &DatabaseSchema,
    model: &Model,
    naming: &NamingContext<'_>,
) {
    out.push(format!("export type {} = {{", model.name));
    for field in model.fields.iter().filter(|f| !f.name.contains('.')) {
        if should_omit_on_record(field) {
            continue;
        }
        let ts = map_model_field_record(schema, model, field, naming);
        let optional = if field.optional { "?" } else { "" };
        let name = naming.field_name(field);
        out.push(format!("  {name}{optional}: {ts};"));
    }
    out.push("};".to_owned());
    out.push(String::new());
}

fn emit_model_selected(
    out: &mut Vec<String>,
    schema: &DatabaseSchema,
    model: &Model,
    naming: &NamingContext<'_>,
) {
    out.push(format!("export type {}Selected = {{", model.name));
    for field in model.fields.iter().filter(|f| !f.name.contains('.')) {
        let ts = map_model_field_selected(schema, model, field, naming);
        let optional = if field.optional || field.is_computed_link() || field.relation_name.is_some()
        {
            "?"
        } else {
            ""
        };
        let name = naming.field_name(field);
        out.push(format!("  {name}{optional}: {ts};"));
    }
    out.push("};".to_owned());
    out.push(String::new());
}

fn emit_model_inputs(
    out: &mut Vec<String>,
    schema: &DatabaseSchema,
    model: &Model,
    naming: &NamingContext<'_>,
) {
    out.push(format!("export type {}CreateScalars = {{", model.name));
    for field in model.fields.iter().filter(|f| !f.name.contains('.')) {
        if field.is_id || should_omit_on_record(field) {
            continue;
        }
        let ts = map_model_field_record(schema, model, field, naming);
        let optional = if field.optional { "?" } else { "" };
        let name = naming.field_name(field);
        out.push(format!("  {name}{optional}: {ts};"));
    }
    out.push("};".to_owned());
    out.push(String::new());

    let stored_overrides: Vec<(&Field, String)> = model
        .fields
        .iter()
        .filter(|f| !f.name.contains('.') && f.is_stored_link())
        .map(|f| (f, naming.field_name(f)))
        .collect();

    if stored_overrides.is_empty() {
        out.push(format!(
            "export type {}CreateInput = {}CreateScalars & {{",
            model.name, model.name
        ));
    } else {
        let omit_keys = stored_overrides
            .iter()
            .map(|(_, n)| format!("\"{n}\""))
            .collect::<Vec<_>>()
            .join(" | ");
        out.push(format!(
            "export type {}CreateInput = Omit<{}CreateScalars, {omit_keys}> & {{",
            model.name, model.name
        ));
        for (field, name) in &stored_overrides {
            let target = field
                .link_target
                .as_deref()
                .or_else(|| field.field_type.link_model_name())
                .unwrap_or("unknown");
            let table = table_for_model_name(schema, target, naming);
            let optional = if field.optional { "?" } else { "" };
            out.push(format!(
                "  {name}{optional}: RecordId<\"{table}\"> | string | {{ connect: {{ id: string }} }} | {{ create: {target}CreateScalars }};"
            ));
        }
    }
    emit_model_nested_write_bags(out, schema, model, naming, false);
    out.push("};".to_owned());
    out.push(String::new());

    out.push(format!("export type {}UpdateInput = {{", model.name));
    for field in model.fields.iter().filter(|f| !f.name.contains('.')) {
        if field.is_id || should_omit_on_record(field) {
            continue;
        }
        let name = naming.field_name(field);
        if field.is_stored_link() {
            let target = field
                .link_target
                .as_deref()
                .or_else(|| field.field_type.link_model_name())
                .unwrap_or("unknown");
            let table = table_for_model_name(schema, target, naming);
            if field.optional {
                out.push(format!(
                    "  {name}?: RecordId<\"{table}\"> | string | {{ connect: {{ id: string }} }} | {{ create: {target}CreateScalars }} | {{ disconnect: true }};"
                ));
            } else {
                out.push(format!(
                    "  {name}?: RecordId<\"{table}\"> | string | {{ connect: {{ id: string }} }} | {{ create: {target}CreateScalars }};"
                ));
            }
        } else {
            let ts = map_model_field_record(schema, model, field, naming);
            out.push(format!("  {name}?: {ts};"));
        }
    }
    emit_model_nested_write_bags(out, schema, model, naming, true);
    out.push("};".to_owned());
    out.push(String::new());
}

fn emit_model_nested_write_bags(
    out: &mut Vec<String>,
    schema: &DatabaseSchema,
    model: &Model,
    naming: &NamingContext<'_>,
    _for_update: bool,
) {
    for field in model.fields.iter().filter(|f| !f.name.contains('.')) {
        let name = naming.field_name(field);
        if let Some(relation) = &field.relation_name {
            let edge_name = resolve_edge_type_name(schema, relation);
            let Some(edge) = schema.edges.iter().find(|e| e.name == edge_name) else {
                continue;
            };
            let dir = if edge.in_model == model.name {
                "out"
            } else if edge.out_model == model.name {
                "in"
            } else {
                continue;
            };
            let far = dir;
            let far_model_name = if dir == "out" {
                edge.out_model.as_str()
            } else {
                edge.in_model.as_str()
            };
            let omit_keys = schema
                .models
                .iter()
                .find(|m| m.name == far_model_name)
                .map(|far_model| {
                    far_model
                        .fields
                        .iter()
                        .filter(|f| {
                            f.is_stored_link()
                                && f.link_target.as_deref() == Some(model.name.as_str())
                        })
                        .map(|f| format!("\"{}\"", naming.field_name(f)))
                        .collect::<Vec<_>>()
                })
                .unwrap_or_default();
            let far_create_ty = if omit_keys.is_empty() {
                format!("{far_model_name}CreateScalars")
            } else {
                format!(
                    "Omit<{far_model_name}CreateScalars, {}>",
                    omit_keys.join(" | ")
                )
            };
            let mut payload_fields = String::new();
            for ef in edge.fields.iter().filter(|f| !f.name.contains('.')) {
                let ef_name = naming.field_name(ef);
                let ts = map_scalar_or_object(None, &ef.field_type, ef, naming);
                let optional = if ef.optional { "?" } else { "" };
                let _ = write!(payload_fields, " {ef_name}{optional}: {ts};");
            }
            out.push(format!("  {name}?: {{"));
            out.push(format!(
                "    create?: Array<{{{payload_fields} {far}: string | {{ create: {far_create_ty} }}; }}>;"
            ));
            out.push(format!(
                "    connect?: Array<({{ {far}: string }} & {{{payload_fields}}}) | {{ id: string }}>;"
            ));
            out.push(format!(
                "    disconnect?: Array<{{ {far}: string }} | {{ id: string }}>;"
            ));
            out.push("  };".to_owned());
        } else if field.is_computed_link() {
            let target = field
                .link_target
                .as_deref()
                .or_else(|| field.field_type.link_model_name())
                .unwrap_or("unknown");
            let back = field.link_opposite_field.as_deref().unwrap_or("id");
            out.push(format!("  {name}?: {{"));
            out.push(format!(
                "    create?: Array<Omit<{target}CreateScalars, \"{back}\">>;"
            ));
            out.push("    connect?: Array<{ id: string }>;".to_owned());
            out.push("    disconnect?: Array<{ id: string }>;".to_owned());
            out.push("  };".to_owned());
        }
    }
}

fn emit_select_type_utils(out: &mut Vec<String>) {
    out.push(
        "/** `true` or nested `{ select, orderBy? }` for a related entity. */".to_owned(),
    );
    out.push("export type SelectArg<S, O = never> =".to_owned());
    out.push("  | boolean".to_owned());
    out.push(
        "  | { select?: S; orderBy?: [O] extends [never] ? never : O | O[] };".to_owned(),
    );
    out.push(String::new());
    out.push(
        "/** Resolve one select entry: `true` → Default; `{ select: N }` → nested payload. */"
            .to_owned(),
    );
    out.push("export type ResolveSelectField<".to_owned());
    out.push("  V,".to_owned());
    out.push("  Default,".to_owned());
    out.push("  NestedSelect,".to_owned());
    out.push("  NestedPayload,".to_owned());
    out.push("> = V extends true".to_owned());
    out.push("  ? Default".to_owned());
    out.push("  : V extends { select?: NestedSelect }".to_owned());
    out.push("    ? NestedPayload".to_owned());
    out.push("    : never;".to_owned());
    out.push(String::new());
}

