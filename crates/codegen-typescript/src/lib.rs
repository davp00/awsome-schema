    out.push("  key: string,".to_owned());
    out.push("  value: unknown,".to_owned());
    out.push("  fieldMeta: FieldSelectMeta,".to_owned());
    out.push("  allMeta: Record<string, Record<string, FieldSelectMeta>>,".to_owned());
